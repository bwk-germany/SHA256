using System.Security.Cryptography;
using System.Xml;
using System.Xml.Serialization;


if (args.Length == 0 || !Directory.Exists(args[0]))
{
    MessageBox.Show(
        "Bitte ziehen Sie ein vorhandenes Verzeichnis auf ManifestCreate.exe oder führen Sie von dort SendTo auf ManifestCreate.exe aus.",
        "ManifestCreate",
        MessageBoxButtons.OK,
        MessageBoxIcon.Error);
    return;
}

string path = args[0];

DocumentManifest manifest = new();

int index = 1;

foreach (string file in Directory.EnumerateFiles(path, "*", SearchOption.AllDirectories).OrderBy(f => f))
        {using FileStream stream = File.OpenRead(file);
         manifest.Document.Add(
             new DocumentEntry{Index = index++,
                               Name  = Path.GetRelativePath(path, file),
                               Size  = stream.Length,
                               Hash  = Convert.ToHexString(SHA256.HashData(stream)).ToLowerInvariant()
                              }
                              );
        }

path = Path.GetFullPath(path).TrimEnd(Path.DirectorySeparatorChar);
string parent = Path.GetDirectoryName(path)!;
string baseName = Path.GetFileName(path);
string tempFile = Path.Combine(parent, baseName + ".xml.tmp");

{using FileStream stream = File.Create(tempFile);
 var settings = new XmlWriterSettings { Indent = true, IndentChars = "    ",  Encoding = System.Text.Encoding.UTF8 };
 using XmlWriter writer = XmlWriter.Create(stream, settings);
 writer.WriteStartDocument();
 writer.WriteComment(@"
Automatically generated using ManifestCreate, available at: https://github.com/bwk-germany/sha256

DO NOT EDIT THIS FILE MANUALLY.
Any modification will cause the SHA-256 checksum in the file name to no longer match the contents of this file.
");
 new XmlSerializer(typeof(DocumentManifest)).Serialize(writer, manifest);
 writer.WriteEndDocument();
}

string sha256;using (FileStream stream = File.OpenRead(tempFile)){sha256 = Convert.ToHexString(SHA256.HashData(stream)).ToLowerInvariant();}
string finalFile = Path.Combine(parent,$"{baseName}.sha256.{sha256}.xml");
File.Move(tempFile, finalFile, overwrite: true); // rename
if (File.Exists(tempFile))  File.Delete(tempFile);

 MessageBoxEx.Show("Es wurde die Manifestdatei\r\n\r\n"+Path.GetFileName(finalFile)+"\r\n\r\nerstellt.","ManifestCreate",800,300,MessageBoxIcon.Information);


