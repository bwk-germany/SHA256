'use strict';
const $=id=>document.getElementById(id);
const encoder=new TextEncoder();
const NL='\r\n';
const COMMENT=`\nAutomatically generated using ManifestCreate, available at: https://github.com/bwk-germany/sha256\n\nDO NOT EDIT THIS FILE MANUALLY.\nAny modification will cause the SHA-256 checksum in the file name to no longer match the contents of this file.\n`;
let working=false, activeUrls=[];
function escapeXml(s){return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;').replace(/'/g,'&apos;');}
function normalize(s){return s.replace(/\\/g,'/').trim();}
function key(s){return normalize(s).toLowerCase();}
function selection(input){
  const files=Array.from(input.files||[]), first=files[0];
  if(!first)return {files:[],root:''};
  const prefix=(first.webkitRelativePath||'').split('/')[0];
  return {root:prefix||'Dokumente',files:files.map(f=>({file:f,name:(f.webkitRelativePath||f.name).split('/').slice(1).join('/')||f.name}))};
}
function setProgress(p,label){$('progress-bar').style.width=`${Math.min(100,Math.max(0,p))}%`;if(label)$('progress-label').textContent=label;}
function status(label,mode=''){$('status').textContent=label;$('status').className='status '+mode;}
function clearResult(){for(const url of activeUrls)URL.revokeObjectURL(url);activeUrls=[];$('downloads').replaceChildren();$('result-log').textContent='';setProgress(0,'Verarbeitung läuft …');status('In Bearbeitung');}
function addDownload(name,bytes,mime,label){const url=URL.createObjectURL(new Blob([bytes],{type:mime}));activeUrls.push(url);const a=document.createElement('a');a.className='download';a.href=url;a.download=name;a.textContent=label||name;$('downloads').append(a);}
function setBusy(b){working=b;updateButtons();}
function updateButtons(){ $('create-start').disabled=working||!$('create-folder').files.length; $('check-start').disabled=working||!$('check-folder').files.length||!$('check-manifest').files.length; }
function localTimestamp(){const d=new Date(),z=n=>String(n).padStart(2,'0');return `${d.getFullYear()}-${z(d.getMonth()+1)}-${z(d.getDate())} ${z(d.getHours())}:${z(d.getMinutes())}:${z(d.getSeconds())}`;}
function buildXml(entries){
  const lines=['<?xml version="1.0" encoding="utf-8"?>',`<!--${COMMENT}-->`, '<DocumentManifest xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xsd="http://www.w3.org/2001/XMLSchema" ManifestVersion="1" HashAlgorithm="SHA-256">'];
  for(const e of entries)lines.push(`    <Document Index="${e.index}" Name="${escapeXml(e.name)}" Hash="${e.hash}" Size="${e.size}" />`);
  lines.push('</DocumentManifest>');
  // UTF-8 BOM and Windows CRLF, as used by XmlWriterSettings(Encoding.UTF8) on Windows.
  let xml = lines.join(NL);xml = xml.replace(/\r\n|\r|\n/g, "\r\n");const content=encoder.encode(xml),out=new Uint8Array(content.length+3);
  out.set([0xef,0xbb,0xbf]);out.set(content,3);return out;
}
async function createManifest(){
  if(working)return;setBusy(true);clearResult();
  try{
    const selected=selection($('create-folder'));const files=selected.files;
    if(!files.length)throw Error('Keine Dateien ausgewählt.');
    // C# OrderBy(f => f) verwendet eine kulturabhängige Sortierung (z. B. de-DE).
    // Ein fester Locale-Wert liefert unabhängig von der Browsersprache dieselbe Reihenfolge.
    const collator = new Intl.Collator("de-DE", { sensitivity: "variant", numeric: false });
    files.sort((a,b)=>collator.compare(a.name,b.name));
    const entries=[];let done=0;
    for(const item of files){
      const hash=await hashFile(item.file);entries.push({index:entries.length+1,name:item.name.replace(/\//g,'\\'),hash,size:item.file.size});
      done++;setProgress(100*done/files.length,`Datei ${done}/${files.length}: ${item.name}`);
      await new Promise(resolve=>setTimeout(resolve,0));
    }
    const bytes=buildXml(entries);const sha=new Sha256().update(bytes).digestHex();
    const filename=`${selected.root}.sha256.${sha}.xml`;
    addDownload(filename,bytes,'application/xml;charset=utf-8','XML-Manifest herunterladen');
    $('result-log').textContent=`OK: ${entries.length} Dateien erfasst.\nSHA-256 der Manifestdatei: ${sha}\nDateiname: ${filename}\n\nDie Manifestdatei wird im Download-Ordner gespeichert, nicht automatisch im übergeordneten Datenverzeichnis.`;
    status('Erstellt','good');setProgress(100,'Manifest erfolgreich erstellt.');
  }catch(e){fail(e);}finally{setBusy(false);}
}
function parseXml(text){
  const doc=new DOMParser().parseFromString(text,'application/xml');
  if(doc.querySelector('parsererror'))throw Error('XML ist syntaktisch ungültig.');
  const root=doc.documentElement;
  if(root.localName!=='DocumentManifest')throw Error('XML-Wurzelelement ist nicht DocumentManifest.');
  const version=root.getAttribute('ManifestVersion')??'1',algo=root.getAttribute('HashAlgorithm')??'SHA-256';
  const entries=[];
  for(const node of root.children){
    if(node.localName!=='Document')continue;
    const size=Number(node.getAttribute('Size')??0);
    if(!Number.isSafeInteger(size)||size<0)throw Error(`Ungültige Dateigröße: ${node.getAttribute('Size')}`);
    entries.push({name:node.getAttribute('Name')||'',hash:node.getAttribute('Hash')||'',size});
  }
  return {version,algo,entries};
}
async function checkManifest(){
  if(working)return;setBusy(true);clearResult();
  const file=$('check-manifest').files[0],sel=selection($('check-folder'));
  const log=['Manifest check',`Date/Time    : ${localTimestamp()}`,`Manifest file: ${file.name}`,`Data path    : ${sel.root}`,''];
  let ok=true;
  try{
    log.push('1. Format, XML content, version and file name');
    const m=/^(.+)\.sha256\.([a-fA-F0-9]{64})\.xml$/.exec(file.name);
    if(m)log.push('OK: File name contains SHA-256 checksum.');else {ok=false;log.push("ERROR: File name does not match pattern '<name>.sha256.<64 hex chars>.xml'.");}
    const manifestBytes=new Uint8Array(await file.arrayBuffer());
    let parsed;
    try{parsed=parseXml(new TextDecoder('utf-8',{fatal:true}).decode(manifestBytes));
      if(Number(parsed.version)!==1){ok=false;log.push(`ERROR: Unsupported manifest version: ${parsed.version}`);}
      else if(parsed.algo.toLowerCase()!=='sha-256'){ok=false;log.push(`ERROR: Unsupported hash algorithm: ${parsed.algo}`);}
      else log.push('OK: XML content, manifest version and hash algorithm are valid.');
    }catch(e){ok=false;log.push('ERROR: XML deserialization failed.',e.message);}
    log.push('');
    if(parsed){
      log.push('2. Manifest checksum from file name');
      if(m){const actual=new Sha256().update(manifestBytes).digestHex(),expected=m[2].toLowerCase();
        if(actual===expected)log.push('OK: SHA-256 checksum in file name matches manifest file content.');
        else{ok=false;log.push('ERROR: SHA-256 checksum in file name does not match manifest file content.',`Expected: ${expected}`,`Actual  : ${actual}`);}
      }
      log.push('');
      const manifestFiles=new Map(),realFiles=new Map();
      for(const e of parsed.entries){const k=key(e.name);if(manifestFiles.has(k))throw Error(`Duplicate file name in manifest: ${e.name}`);manifestFiles.set(k,e);}
      for(const e of sel.files){const k=key(e.name);if(realFiles.has(k))throw Error(`Duplicate path differing only by case: ${e.name}`);realFiles.set(k,e);}
      log.push('3. File existence');let existOk=true;
      for(const [k,e] of manifestFiles)if(!realFiles.has(k)){ok=false;existOk=false;log.push(`ERROR: Missing file: ${normalize(e.name)}`);}
      for(const [k,e] of realFiles)if(!manifestFiles.has(k)){ok=false;existOk=false;log.push(`ERROR: Extra file not listed in manifest: ${normalize(e.name)}`);}
      if(existOk)log.push('OK: All files exist and no extra files were found.');
      log.push('','4. File size');let sizeOk=true;
      for(const e of parsed.entries){const r=realFiles.get(key(e.name));if(!r)continue;
        if(r.file.size!==e.size){ok=false;sizeOk=false;log.push(`ERROR: Size mismatch: ${e.name}`,`Expected: ${e.size}`,`Actual  : ${r.file.size}`);}
      }
      if(sizeOk)log.push('OK: All file sizes match.');
      log.push('','5. File SHA-256 checksums');let hashOk=true,done=0;
      for(const e of parsed.entries){const r=realFiles.get(key(e.name));if(!r)continue;
        const actual=await hashFile(r.file),expected=e.hash.toLowerCase();done++;
        setProgress(100*done/Math.max(1,parsed.entries.length),`Datei ${done}/${parsed.entries.length}: ${e.name}`);
        if(actual!==expected){ok=false;hashOk=false;log.push(`ERROR: SHA-256 mismatch: ${e.name}`,`Expected: ${expected}`,`Actual  : ${actual}`);}
        await new Promise(resolve=>setTimeout(resolve,0));
      }
      if(hashOk)log.push('OK: All SHA-256 checksums match.');
      log.push('','6. Result',ok?'OK: Manifest check successful.':'ERROR: Manifest check failed.');
    }
  }catch(e){ok=false;log.push('',`ERROR: ${e.message}`,'','6. Result','ERROR: Manifest check failed.');}
  const logname=file.name.replace(/\.xml$/,'')+'.check.log';
  const logtext=log.join(NL)+NL;
  // .NET File.WriteAllLines(..., Encoding.UTF8) produces a UTF-8 BOM.
  addDownload(logname,new Uint8Array([0xef,0xbb,0xbf,...encoder.encode(logtext)]),'text/plain;charset=utf-8','Prüfprotokoll herunterladen');
  $('result-log').textContent=logtext;status(ok?'Prüfung erfolgreich':'Abweichungen gefunden',ok?'good':'bad');
  setProgress(100,ok?'Alle Prüfungen erfolgreich.':'Prüfung abgeschlossen – Einzelheiten im Protokoll.');setBusy(false);
}
function fail(e){status('Fehler','bad');$('result-log').textContent=`ERROR: ${e.message}`;setProgress(0,'Verarbeitung fehlgeschlagen.');}
